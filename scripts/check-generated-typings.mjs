#!/usr/bin/env node
/**
 * 生成物类型文件自检（2026-10-19 事故后新增）。
 *
 * ## 为什么需要它
 *
 * 2026-10-19 实测事故：一次被中断的工具链运行（WorkBuddy broker FS shim 超时）
 * 把 `src/typings/auto-imports.d.ts` **截断成 0 字节**，随后 `pnpm typecheck` 报出
 * **2045 个** `Cannot find name 'ref'` / `defineAsyncComponent` 之类的错误。
 *
 * 表面看是"全项目崩了"，实际是一个生成物被清空。排查这类问题最费时间的地方在于：
 * 错误信息完全不指向真凶（2045 个错误分散在几百个文件里）。
 *
 * 本脚本在 typecheck **之前**跑，几毫秒就能指出"是这个文件空了"。
 *
 * ## 判据
 *
 * 每个生成物必须：① 存在 ② 体积大于下限 ③ 含关键标记。
 * 三项任一不满足即 FAIL，并直接给出修复命令。
 *
 * 用法：`node scripts/check-generated-typings.mjs`
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')

/** 生成物清单：体积下限故意设得很宽松，只用来识别"被清空/几乎清空" */
const TARGETS = [
  {
    file: 'src/typings/auto-imports.d.ts',
    minBytes: 1500,
    markers: ['declare global', 'defineAsyncComponent', 'const computed'],
    regenerate: '启动一次 vite（`pnpm dev` 会触发 unplugin-auto-import 重写该文件）'
  },
  {
    file: 'src/typings/components.d.ts',
    minBytes: 5000,
    markers: ['GlobalComponents', 'Generated by unplugin-vue-components'],
    regenerate: '启动一次 vite（unplugin-vue-components 会在启动时重写）'
  },
  {
    file: 'src/typings/i18n.d.ts',
    minBytes: 50_000,
    markers: ['auto-generated by scripts/generate-i18n-types.mjs', 'export type I18nKeys'],
    regenerate: 'pnpm gen:i18n'
  }
]

const problems = []

for (const target of TARGETS) {
  const abs = path.join(root, target.file)
  if (!fs.existsSync(abs)) {
    problems.push(`${target.file}: 文件不存在（修复：${target.regenerate}）`)
    continue
  }
  const content = fs.readFileSync(abs, 'utf8')
  const bytes = Buffer.byteLength(content, 'utf8')

  if (bytes < target.minBytes) {
    problems.push(
      `${target.file}: 只有 ${bytes} 字节（下限 ${target.minBytes}）—— 疑似被工具链中断截断。\n` +
        `    修复：git checkout -- ${target.file}（该文件已入库）；或 ${target.regenerate}`
    )
    continue
  }

  const missing = target.markers.filter((marker) => !content.includes(marker))
  if (missing.length > 0) {
    problems.push(
      `${target.file}: 缺少关键标记 ${missing.map((m) => `\`${m}\``).join(', ')}` +
        `\n    修复：${target.regenerate}`
    )
  }
}

if (problems.length > 0) {
  console.error('[check-generated-typings] FAIL —— 生成物类型文件异常（会导致大规模假类型错误）：\n')
  for (const problem of problems) {
    console.error(`  ✖ ${problem}`)
  }
  console.error(
    '\n提示：这类问题的典型症状是 typecheck 报出成百上千个 "Cannot find name \'ref\' / defineAsyncComponent"，' +
      '\n      看起来像全项目崩了，实际只是生成物被清空。'
  )
  process.exit(1)
}

console.log(`[check-generated-typings] OK —— ${TARGETS.length} 个生成物类型文件完整`)
