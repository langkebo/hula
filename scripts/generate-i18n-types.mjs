import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const localesDir = path.resolve(__dirname, '../locales/zh-CN')
const outputPath = path.resolve(__dirname, '../src/typings/i18n.d.ts')

function generateTypes() {
  const files = fs.readdirSync(localesDir).filter(file => file.endsWith('.json'))
  const types = {}

  for (const file of files) {
    const part = path.basename(file, '.json')
    const content = JSON.parse(fs.readFileSync(path.join(localesDir, file), 'utf-8'))
    types[part] = content
  }

  const typeContent = `/**
 * This file is auto-generated by scripts/generate-i18n-types.mjs
 * DO NOT EDIT MANUALLY
 */

export type I18nKeys = ${JSON.stringify(types, null, 2)}
`

  fs.writeFileSync(outputPath, typeContent)
  console.log(`[i18n] Generated types to ${outputPath}`)
}

generateTypes()
